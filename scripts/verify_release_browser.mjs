/** Real desktop/mobile release checks. Set PLAYWRIGHT_MODULE to an installed module. */
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.AF_BROWSER_BASE || 'http://127.0.0.1:3000';
const output=process.env.AF_BROWSER_OUTPUT || '/tmp/afterfire-release-browser';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
page.setDefaultTimeout(60000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const requests=[];page.on('request',r=>{if(r.url().includes('/global/hotspots'))requests.push(r.url());});
const report={};
const overflow=()=>page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
try{
 await page.goto(base+'/explorer?period=custom&start=2023-07-20&end=2023-07-22&sensor=MODIS&map=27.92,36.14,27.98,36.20&z=11');
 await page.getByRole('link',{name:'Analyze candidate',exact:true}).first().waitFor();
 assert.equal(await page.getByLabel('Fire data source',{exact:true}).inputValue(),'online');
 assert.equal(await page.getByRole('button',{name:'Last 30 days',exact:true}).count(),0);
 const filters=page.getByText('Area, dates and sensor filters',{exact:true});
 if(await filters.count() && !await filters.evaluate(el=>el.closest('details').open)) await filters.click();
 await page.getByRole('button',{name:'Draw / edit circle',exact:true}).waitFor();
 report.explorer_desktop_overflow=await overflow();
 await page.screenshot({path:output+'-explorer-desktop.png',fullPage:true});
 const initialRequests=[...requests];
 assert(!initialRequests.some(u=>new URL(u).searchParams.get('bbox')==='6.3,35.3,18.9,47.2'));
 report.initial_hotspot_requests=initialRequests;
 await page.getByLabel('Fire data source',{exact:true}).selectOption('archive');
 await page.getByLabel('Fire data source',{exact:true}).selectOption('online');
 await page.waitForFunction(()=>new URLSearchParams(location.search).get('source')==='online' && new URLSearchParams(location.search).get('period')==='7d');
 report.source_switch_atomic=true;
 await page.getByRole('button',{name:'Custom date range',exact:true}).click();
 await page.getByLabel('From',{exact:true}).fill('2023-07-20');
 await page.getByLabel('To',{exact:true}).fill('2023-07-22');
 await page.getByRole('link',{name:'Analyze candidate',exact:true}).first().waitFor();
 await page.getByRole('link',{name:'Analyze candidate',exact:true}).first().click();
 await page.getByText('Satellite Recovery Story',{exact:true}).waitFor();
 report.selected_event_url=page.url();
 // Viewport boundaries can change candidate membership and therefore its identity.
 // Open the exact independently published fixture-free event for science QA.
 const savedStart=performance.now();
 await page.goto(base+'/events/'+(process.env.AF_SCIENCE_EVENT || 'global-d77c8ac8d89369a61e7125f78cfe2e76'));
 await page.getByText(/Cached scientific analysis/).waitFor();
 report.cached_science_visible_seconds=(performance.now()-savedStart)/1000;
 await page.getByRole('heading',{name:'Territory recovery map',exact:true}).waitFor();
 const frameStart=performance.now();
 await page.getByRole('button',{name:'3. Immediate Post-Fire',exact:true}).click();
 await page.waitForFunction(()=>[...document.querySelectorAll('img.leaflet-image-layer')].some(i=>i.complete&&i.naturalWidth>0));
 report.requested_frame_seconds=(performance.now()-frameStart)/1000;
 await page.getByLabel('Vegetation index',{exact:true}).selectOption('EVI');
 await page.getByRole('heading',{name:'Recovery Intelligence · EVI',exact:true}).waitFor();
 await page.getByLabel('Compare real observations',{exact:true}).check();
 await page.getByLabel('Before observation',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Reburn History',exact:true}).click();
 report.science_desktop_overflow=await overflow();
 await page.screenshot({path:output+'-science-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.reload();await page.getByText(/Cached scientific analysis/).waitFor();
 await page.getByRole('heading',{name:'Territory recovery map',exact:true}).waitFor();
 report.science_mobile_overflow=await overflow();
 await page.screenshot({path:output+'-science-mobile.png',fullPage:true});
 await page.goto(base+'/explorer?period=custom&start=2023-07-20&end=2023-07-22&sensor=MODIS&map=27.92,36.14,27.98,36.20&z=11');
 await page.getByRole('button',{name:'Fire data',exact:false}).click();
 await page.getByRole('link',{name:'Analyze candidate',exact:true}).first().waitFor();
 report.explorer_mobile_overflow=await overflow();
 if(await filters.count() && !await filters.evaluate(el=>el.closest('details').open)) await filters.click();
 await page.getByLabel('From',{exact:true}).fill('2025-01-01');
 await page.getByText('Enter valid dates in chronological order.',{exact:true}).waitFor();
 assert.equal(await page.getByRole('link',{name:'Analyze candidate',exact:true}).count(),0);
 report.invalid_dates_clear_candidates=true;
 await page.screenshot({path:output+'-explorer-mobile.png',fullPage:true});
 report.errors=errors;
 assert(!errors.length&&!report.explorer_desktop_overflow&&!report.explorer_mobile_overflow&&!report.science_desktop_overflow&&!report.science_mobile_overflow);
 await fs.writeFile(output+'.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report));
}finally{await browser.close();}
